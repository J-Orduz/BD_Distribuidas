	estudiante_id VARCHAR(12),
	hobbie_id INTEGER,
	cantidad_horas INTEGER,
	PRIMARY KEY (estudiante_id, hobbie_id),
	FOREIGN KEY (estudiante_id) REFERENCES ESTUDIANTES(id_estudiante),
